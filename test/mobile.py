import asyncio, sys, math
from harness import *

async def main():
    async with async_playwright() as p:
        b, page, logs = await open_page(p, 'phone', True)
        page.set_default_timeout(120000)
        await shot(page, 'p-m01-intro')
        await page.tap('#bEnter'); await page.wait_for_timeout(400)
        await shot(page, 'p-m02-lobby')
        await page.evaluate("window.__test.goView(window.__test.PLACES.find(p => p.id === 'yard').view())"); await page.wait_for_timeout(700)
        await shot(page, 'p-m03-yard')
        await page.evaluate("window.__test.openRide('coaster')"); await page.wait_for_timeout(300)
        await shot(page, 'p-m04-ridecard')
        await page.tap('#rcGentle'); await page.wait_for_timeout(500)
        C = await page.evaluate("window.__test.COASTER.iCrest * window.__test.COASTER.ds")
        await page.evaluate(f"window.__test.ride.phase = 'test'; window.__test.ride.s = {C + 12}; window.dispatchEvent(new Event('resize'))"); await page.wait_for_timeout(700)
        await shot(page, 'p-m05-coaster')
        await page.evaluate("window.__test.endRide(false)"); await page.wait_for_timeout(500)
        await page.evaluate("window.__test.startRide('dive', false)"); await page.wait_for_timeout(500)
        await page.evaluate("window.__test.ride.u = 0.66; window.__test.ride.phase = 'run'; window.__test.ride.paused = true; window.dispatchEvent(new Event('resize'))"); await page.wait_for_timeout(1500)
        await shot(page, 'p-m06-dive')
        await page.evaluate("window.__test.endRide(false)"); await page.wait_for_timeout(500)
        await page.evaluate("window.__test.award('explorer')"); await page.wait_for_timeout(300)
        await shot(page, 'p-m07-award')
        await page.tap('#bBadges'); await page.wait_for_timeout(400)
        await shot(page, 'p-m08-badges')
        await page.tap('#bgClose'); await page.wait_for_timeout(300)
        await page.evaluate("window.__test.goView(window.__test.PLACES.find(p => p.id === 'rae').view())"); await page.wait_for_timeout(600)
        await page.tap('#askBtn'); await page.wait_for_timeout(300)
        await page.tap('#gChips .chip >> nth=2'); await page.wait_for_timeout(500)
        await shot(page, 'p-m09-rae')
        print(errs(logs))
        await b.close()
asyncio.run(main())
